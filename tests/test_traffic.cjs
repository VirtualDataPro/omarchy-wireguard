const fs = require('fs');
const vm = require('vm');
const assert = require('assert/strict');
const traffic = {};
vm.createContext(traffic);
vm.runInContext(fs.readFileSync('Traffic.js', 'utf8'), traffic);
const p = (rx, tx, device = 'wg0') => ({device, counters: {rx, tx}});
let first = traffic.sample(null, p(1000, 200), 1);
assert.equal(first.down, 0);
let next = traffic.sample(first, p(3000, 1200), 3);
assert.equal(next.down, 1000);
assert.equal(next.up, 500);
assert.equal(traffic.sample(next, p(100, 100), 5).down, 0, 'counter resets must not spike');
assert.equal(traffic.sample(next, p(9000, 9000, 'wg1'), 5).down, 0, 'new devices need a baseline');
assert.equal(traffic.sample(next, p(9000, 9000), 40).down, 0, 'resume from sleep resets baseline');
assert.equal(traffic.sample(next, null, 5).down, 0);
console.log('Traffic counter tests passed');
const previous = [{uuid: 'a', active: true}, {uuid: 'b', active: false}];
assert.equal(traffic.dropped(previous, [], {}).length, 1);
assert.equal(traffic.dropped(previous, [], {a: true}).length, 0, 'intentional stops do not notify');
assert.equal(traffic.dropped(previous, previous, {}).length, 0);
assert.equal(traffic.dropped([], [], {}).length, 0, 'first poll does not notify');
console.log('Drop notification transition tests passed');
